#[inline]
pub fn glyph(ch: u8) -> [u8; 8] {
    FONT8[(ch & 0x7f) as usize]
}

pub fn blit_char(
    fb: &mut [u8],
    stride: i32,
    fb_w: i32,
    fb_h: i32,
    x: i32,
    y: i32,
    ch: u8,
    color: [u8; 4],
    scale: i32,
) {
    let g = glyph(ch);
    let s = scale.max(1);
    for row in 0..8 {
        let bits = g[row as usize];
        for col in 0..8 {
            if (bits & (1 << col)) == 0 {
                continue;
            }
            for dy in 0..s {
                for dx in 0..s {
                    let px = x + col * s + dx;
                    let py = y + row * s + dy;
                    if px < 0 || py < 0 || px >= fb_w || py >= fb_h {
                        continue;
                    }
                    let i = ((py * stride + px) * 4) as usize;
                    if i + 3 < fb.len() {
                        fb[i] = color[0];
                        fb[i + 1] = color[1];
                        fb[i + 2] = color[2];
                        fb[i + 3] = color[3];
                    }
                }
            }
        }
    }
}

pub fn blit_text(
    fb: &mut [u8],
    stride: i32,
    fb_w: i32,
    fb_h: i32,
    mut x: i32,
    y: i32,
    text: &[u8],
    color: [u8; 4],
    scale: i32,
) {
    let adv = 8 * scale.max(1);
    for &ch in text {
        blit_char(fb, stride, fb_w, fb_h, x, y, ch, color, scale);
        x += adv;
    }
}
